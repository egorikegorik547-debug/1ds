function runAct(game: Game, a: ActKey) {
  switch (a) {
    case 'claim':
      game.setTool('claim');
      break;
    case 'selectAll':
      game.selectAll();
      break;
    case 'chop':
      game.setTool('chop');
      break;
    default:
      game.onHotkey?.(a);
  }
}

